// Bundle src/lib/engine into backend/engine/engine.cjs for the backend.
//
//   node scripts/build-engine.mjs          write the bundle
//   (imported)  bundleEngine()             the bundle text, for the drift test
//
// Deterministic for a given esbuild version and source, so the drift test can
// compare byte for byte.
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const ENGINE_BUNDLE_PATH = join(root, 'backend', 'engine', 'engine.cjs');

const HEADER =
  '// GENERATED by `npm run build:engine` from src/lib/engine - DO NOT EDIT.\n' +
  '// The backend runs the same engine source as the browser; engineBundle.test.ts\n' +
  '// fails if this file differs from a fresh build.\n';

export async function bundleEngine() {
  const result = await build({
    entryPoints: [join(root, 'src', 'lib', 'engine', 'index.ts')],
    bundle: true,
    platform: 'node',
    format: 'cjs',
    target: 'node18',
    alias: { '@': join(root, 'src') },
    write: false,
    legalComments: 'none',
    logLevel: 'silent',
    absWorkingDir: root,
  });
  return HEADER + result.outputFiles[0].text;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(ENGINE_BUNDLE_PATH, await bundleEngine());
  console.log(`wrote ${ENGINE_BUNDLE_PATH}`);
}
